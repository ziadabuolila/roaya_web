export default function FaqList() {
  const [openItems, setOpenItems] = useState<Record<string, boolean>>({});
  const [openCategories, setOpenCategories] = useState<Record<string, boolean>>({});

  const toggleItem = (id: string) => {
    setOpenItems((prev) => {
      // Close all other items in the same category
      const newOpenItems: Record<string, boolean> = {};
      // Keep items from other categories open
      Object.keys(prev).forEach((key) => {
        if (key !== id) {
          newOpenItems[key] = false;
        }
      });
      // Toggle the clicked item
      newOpenItems[id] = !prev[id];
      return newOpenItems;
    });
  };

  const toggleCategory = (id: string) => {
    setOpenCategories((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  return (
    <div className="faq-container">
      {faqCategories.map((category) => (
        <div key={category.id} className="faq-category">
          <button
            className="faq-category-toggle"
            onClick={() => toggleCategory(category.id)}
          >
            <span className="category-number">{category.id === "about" ? "01" : category.id === "payment" ? "02" : category.id === "software" ? "03" : category.id === "security" ? "04" : "05"}</span>
            <category.icon size={24} />
            <span>{category.title}</span>
            <span className="category-count">{category.items.length}</span>
            <Plus
              size={20}
              className={`chevron ${openCategories[category.id] ? "open" : ""}`}
            />
          </button>
          <div className={`faq-category-content ${openCategories[category.id] ? "open" : ""}`}>
            {category.items.map((item) => (
              <div key={item.id} className="faq-item">
                <button
                  className="faq-toggle"
                  onClick={() => toggleItem(item.id.toString())}
                  aria-expanded={openItems[item.id.toString()]}
                >
                  <span className="faq-number">{String(item.id).padStart(2, "0")}</span>
                  <span className="faq-question">{item.question}</span>
                  <span className="faq-icon">
                    {openItems[item.id.toString()] ? <Minus size={18} /> : <Plus size={18} />}
                  </span>
                </button>
                <div className={`faq-answer ${openItems[item.id.toString()] ? "open" : ""}`}>
                  <p>{item.answer}</p>
                </div>
              </div>
            ))}
          </div>
        </div>
      ))}
    </div>
  );
}
